// node tools/convert-old.js recipes.js [recipes-extra.js] > cookbook-old.js
// Turns the old format  [title, meals, minutes, serves, [[amount, unit, name], ...], "step|step|step"]
// into new cookbook entries: ingredient names are matched to the catalog, ml becomes grams,
// canned legumes are named canned, sweet/savoury meals are re-tagged, ready-made dishes are dropped.
// Anything it cannot match is written as ["?name", amount] so check.js points at exactly what to add to ingredients.js.
const vm=require('vm'),fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..'),ctx={console};ctx.window=ctx;vm.createContext(ctx);
for(const f of ['kitchen.js','ingredients.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),ctx,{filename:f});
const K=ctx.KITCHEN;
const files=process.argv.slice(2);if(!files.length){console.error('usage: node tools/convert-old.js recipes.js [recipes-extra.js] > cookbook-old.js');process.exit(1)}
for(const f of files)vm.runInContext(fs.readFileSync(f,'utf8'),ctx,{filename:f});
const old=[...((ctx.MEAL_DATA||{}).recipes||[]),...(ctx.MEAL_EXTRA||[])];

const READY=/\b(burgers?|hamburgers?|cheeseburgers?|hot ?dogs?|nuggets?|fish (fingers|sticks)|corn dogs?|fast food|takeaway|ready[- ]?(made|meal))\b/i;
const SWEET=/\b(desserts?|cakes?|cookies?|brownies?|muffins?|cupcakes?|pudding|ice cream|mousse|cheesecake|custard|fudge|truffles?|sorbet|tiramisu|compote|panna cotta|flapjacks?|crumble|parfait|banana bread|waffles?|donuts?|doughnuts?|macarons?|tart)\b/i;
// grams per ml, by ingredient id (everything else is treated like water)
const DENS={flour:.55,"baking-powder":.9,"baking-soda":.9,sugar:.85,cocoa:.45,salt:1.2,oats:.4,oil:.92,"olive-oil":.92,honey:1.4,"maple-syrup":1.4,cumin:.45,paprika:.45,"smoked-paprika":.45,turmeric:.45,cinnamon:.45,oregano:.3,thyme:.3,"chilli-powder":.45,"chilli-flakes":.4,"garam-masala":.45,"black-pepper":.45};
const MEALMAP={Breakfast:"wake",Snack:"bite",Lunch:"big",Dinner:"big",Dessert:"treat",Main:"big"};
const slug=s=>s.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const out=[],skipped=[],unknown=new Set(),used=new Set();
const fixTitle=t=>t.replace(/'S\b/g,"'s");
for(const r of old){
  let[title,meals,min,serv,ing,steps]=r;title=fixTitle(String(title));
  if(READY.test(title)){skipped.push(title+' (ready-made dish)');continue}
  let mk=[...new Set((Array.isArray(meals)?meals:String(meals).split(/[ ,|]+/)).map(m=>MEALMAP[m]).filter(Boolean))];
  const sweet=SWEET.test(title);
  if(sweet)mk=mk.filter(m=>m!=='big');if(sweet&&!mk.includes('treat')&&!mk.includes('wake'))mk.push('treat');
  if(!sweet&&mk.includes('treat')&&ing.filter(g=>K.match(g[2])[0]&&/chicken|beef|pork|lamb|fish|tuna|prawn|onion|garlic|rice|pasta/.test(K.match(g[2])[0])).length>=3)mk=mk.filter(m=>m!=='treat');
  if(!mk.length)mk=[sweet?'treat':'big'];
  let id=slug(title),n=2;while(used.has(id))id=slug(title)+'-'+n++;used.add(id);
  let stepList=String(steps).split('|');
  const rows=[];
  for(const g of ing){
    const[amt,unit,name]=g,m=K.match(name),iid=m[0];
    if(!iid){unknown.add(String(name).toLowerCase());rows.push(['?'+name,amt]);continue}
    let v;
    if(unit==='pcs')v=amt+'pc';
    else if(unit==='ml')v=Math.round(amt*(DENS[iid]||1)*10)/10;
    else if(unit==='l')v=amt*1000;
    else if(unit==='kg')v=amt*1000;
    else v=amt;
    // canned legumes: first plain mention in the method becomes the canned name
    const e=K.ING[iid];
    if(e.f.has('canned')){const re=new RegExp('\\b'+String(name).split(' ').pop().replace(/s$/,'')+'s?\\b','i');let done=false;
      stepList=stepList.map(s=>{if(done||!re.test(s)||/canned|tinned/i.test(s))return s;done=true;return s.replace(re,x=>'canned '+x)})}
    rows.push([iid,v]);
  }
  out.push({id,name:title,meal:mk.join(','),time:min,serves:serv,ing:rows,steps:stepList,legacy:true});
}
console.log('/* generated by tools/convert-old.js: review, then replace plain step text with {ingredient-id} placeholders over time.\n   "legacy:true" turns off the placeholder lint for these recipes. */');
console.log('KITCHEN.add('+JSON.stringify(out,null,1).replace(/\n\s+/g,' ').replace(/\[ /g,'[').replace(/ \]/g,']')+');');
console.error(`${out.length} recipes converted, ${skipped.length} skipped`);skipped.forEach(s=>console.error('  skipped:',s));
if(unknown.size){console.error('Unknown ingredients (add these to ingredients.js, then run tools/check.js):');[...unknown].sort().forEach(u=>console.error('  '+u))}
