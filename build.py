#!/usr/bin/env python3
"""Meal Roulette: build helper.

What it does
  1. BUNDLE: joins every cookbook/*.js into one file, cookbook.bundle.js, so the app downloads 1 file instead of ~110.
     The recipe data is compacted (no pretty-print whitespace), each file runs inside its own try/catch so one bad file
     cannot stop the rest, and the result is the same KITCHEN.add(...) calls in the same order.
     You keep editing the individual files in cookbook/; the bundle is generated, never edited by hand.
  2. SYNC: the loader list (var FILES=[...] in index.html) is the single source of truth. sw.js (the offline cache) gets the
     same list plus index.html, fonts, icons and the manifest, and its version (V) is bumped whenever that list changes.

Commands (run from the folder that holds index.html, sw.js and cookbook/):
  python3 build.py check            report problems; changes nothing (exit code 1 if something needs attention)
  python3 build.py build            bundle + sync: the one to run before every deploy
  python3 build.py bundle           only (re)build cookbook.bundle.js; the first run also switches index.html to load the bundle
  python3 build.py sync [--add]     only rewrite sw.js from index.html; --add also lists new craft/*.js files in the loader
  python3 build.py sync --bump      bump the sw.js version even if nothing changed (use after editing a font or icon)

Order of the recipe files is kept in cookbook/order.txt (created on the first bundle, from the order index.html loads them in).
A new cookbook/*.js file is appended to that list automatically.
"""
import glob, json, os, re, sys

HTML, SW, BUNDLE, ORDER = "index.html", "sw.js", "cookbook.bundle.js", "cookbook/order.txt"
FILES_RE = re.compile(r"(var FILES=\[)(.*?)(\];)", re.S)
SWLIST_RE = re.compile(r"(,F=\[)(.*?)(\];)", re.S)
V_RE = re.compile(r'const V="mr-v(\d+)"')
HEAD = ["./", "index.html"]
CALL_RE = re.compile(r"\A\s*(?:/\*.*?\*/\s*)?KITCHEN\.add\(\s*(.*?)\s*\);\s*\Z", re.S)


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(s)


def quoted(s):
    return re.findall(r'"([^"]+)"', s)


def js(items):
    return ",".join('"%s"' % x for x in items)


def loader_files(html):
    m = FILES_RE.search(html)
    if not m:
        sys.exit("Could not find var FILES=[...] in " + HTML)
    return quoted(m.group(2))


def set_loader(html, files):
    return FILES_RE.sub(lambda m: m.group(1) + js(files) + m.group(3), html, count=1)


# ---------------------------------------------------------------- bundle
def cookbook_order(files):
    """recipe files in load order: order.txt if present, else the order the loader lists them; new files are appended"""
    on_disk = sorted(f.replace(os.sep, "/") for f in glob.glob("cookbook/*.js"))
    if os.path.exists(ORDER):
        order = [l.strip() for l in read(ORDER).splitlines() if l.strip() and not l.startswith("#")]
    else:
        order = [f for f in files if f.startswith("cookbook/")]
    order = [f for f in order if f != BUNDLE]
    new = [f for f in on_disk if f not in order]
    return order + new, new


def compact(name, text):
    """the file's code, as small as safely possible"""
    m = CALL_RE.match(text)
    if not m:
        return text.strip() + "\n", "kept as written (not a single KITCHEN.add call)"
    body = m.group(1)
    try:
        data = json.loads(body)
    except ValueError:
        return "KITCHEN.add(" + body + ");", "kept as written (hand-written, not JSON)"
    out = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    if json.loads(out) != data:
        sys.exit("Compacting changed the data of " + name + "; stopping.")
    return "KITCHEN.add(" + out + ");", None


def make_bundle(files):
    order, new = cookbook_order(files)
    missing = [f for f in order if not os.path.exists(f)]
    if missing:
        sys.exit("Listed in " + ORDER + " but not on disk: " + ", ".join(missing))
    parts = ["/* cookbook.bundle.js: GENERATED by build.py from cookbook/*.js (%d files). Edit those, then run: python3 build.py build */" % len(order)]
    notes, before, after = [], 0, 0
    for f in order:
        text = read(f)
        code, note = compact(f, text)
        if note:
            notes.append((f, note))
        before += len(text.encode("utf-8"))
        parts.append("try{" + code + "\n}catch(e){console.error(" + json.dumps(f) + ",e)}")
    out = "\n".join(parts) + "\n"
    return out, order, new, notes, before


def bundle():
    html = read(HTML)
    files = loader_files(html)
    out, order, new, notes, before = make_bundle(files)
    write(BUNDLE, out)
    write(ORDER, "# load order of the recipe files (bundled in this order); new files are appended by build.py\n" + "\n".join(order) + "\n")
    print("%s: %d files, %.0f KB -> %.0f KB" % (BUNDLE, len(order), before / 1024, len(out.encode("utf-8")) / 1024))
    for f in new:
        print("  new file added to the order: " + f)
    for f, n in notes:
        print("  " + f + ": " + n)
    cook = [i for i, f in enumerate(files) if f.startswith("cookbook/")]
    if cook or BUNDLE not in files:
        at = cook[0] if cook else None
        rest = [f for f in files if not f.startswith("cookbook/")]
        if at is None:
            sys.exit("index.html lists no cookbook files to replace; add \"%s\" to var FILES by hand." % BUNDLE)
        rest.insert(at, BUNDLE)
        write(HTML, set_loader(html, rest))
        print("index.html now loads %s instead of %d separate files" % (BUNDLE, len(cook)))


# ---------------------------------------------------------------- lists
def unlisted(files):
    found = sorted(glob.glob("craft/*.js"))
    return [f.replace(os.sep, "/") for f in found if f.replace(os.sep, "/") not in files]


def add_unlisted(files, new):
    out = list(files)
    for f in new:
        at = max((i for i, x in enumerate(out) if x.startswith("craft/")), default=None)
        if at is None:
            sys.exit("No craft/ entries to insert next to; add %s by hand." % f)
        out.insert(at + 1, f)
    return out


def sw_list(files, sw):
    m = SWLIST_RE.search(sw)
    if not m:
        sys.exit("Could not find F=[...] in " + SW)
    old = quoted(m.group(2))
    extra = [x for x in old if x not in files and x not in HEAD and not x.startswith("cookbook/")]  # fonts, icons, manifest stay as they are
    return HEAD + files + extra, old, m


def check():
    html = read(HTML)
    files = loader_files(html)
    sw_new, sw_old, _ = sw_list(files, read(SW))
    problems = []
    print("%d scripts in the loader, %d entries in the offline cache" % (len(files), len(sw_new)))
    missing = [f for f in sw_new if f != "./" and not os.path.exists(f)]
    if missing:
        problems.append(("Listed but missing on disk (run build, or add the file)", missing))
    extra = unlisted(files)
    if extra:
        problems.append(("craft/ files nobody loads (run: sync --add)", extra))
    dup = sorted({f for f in files if files.count(f) > 1})
    if dup:
        problems.append(("Listed twice", dup))
    if sw_new != sw_old:
        problems.append(("sw.js list is out of step with index.html (run: sync)", []))
    if os.path.isdir("cookbook"):
        if BUNDLE not in files:
            problems.append(("index.html still loads the cookbook files one by one (run: bundle)", []))
        else:
            fresh = make_bundle(files)[0]
            if not os.path.exists(BUNDLE) or read(BUNDLE) != fresh:
                problems.append((BUNDLE + " is out of date with cookbook/ (run: build)", []))
            else:
                print("%s is up to date" % BUNDLE)
    for label, items in problems:
        print(label + (":" if items else ""))
        for x in items:
            print("   " + x)
    print("All good." if not problems else "Needs attention.")
    return 1 if problems else 0


def sync(add, bump):
    html, sw = read(HTML), read(SW)
    files = loader_files(html)
    if add:
        new = unlisted(files)
        if new:
            files = add_unlisted(files, new)
            html = set_loader(html, files)
            write(HTML, html)
            print("Added to the loader: " + ", ".join(new))
    sw_new, sw_old, m = sw_list(files, sw)
    changed = sw_new != sw_old
    if changed:
        sw = sw[:m.start()] + m.group(1) + js(sw_new) + m.group(3) + sw[m.end():]
        print("sw.js list updated (%d -> %d entries)" % (len(sw_old), len(sw_new)))
    if changed or bump:
        v = V_RE.search(sw)
        if not v:
            sys.exit('Could not find const V="mr-vNN" in ' + SW)
        n = int(v.group(1)) + 1
        sw = V_RE.sub('const V="mr-v%d"' % n, sw, count=1)
        write(SW, sw)
        print("Version bumped to mr-v%d" % n)
    else:
        print("sw.js already matches index.html.")


if __name__ == "__main__":
    a = sys.argv[1:]
    cmd = a[:1]
    if cmd == ["check"]:
        sys.exit(check())
    if cmd == ["bundle"]:
        bundle()
    elif cmd == ["sync"]:
        sync("--add" in a, "--bump" in a)
    elif cmd == ["build"]:
        bundle()
        sync("--add" in a, "--bump" in a)
    else:
        print(__doc__)
        sys.exit(2)
